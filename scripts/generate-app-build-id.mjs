import { createHash } from "crypto";
import { execFileSync } from "child_process";
import { writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outputPath = join(__dirname, "..", "lib", "app-build-id.generated.ts");
const repoRoot = join(__dirname, "..");

function resolveGitShortHash() {
  try {
    return execFileSync("git", ["rev-parse", "--short=12", "HEAD"], {
      cwd: repoRoot,
      encoding: "utf8",
    }).trim();
  } catch {
    return createHash("sha256")
      .update(String(Date.now()))
      .digest("hex")
      .slice(0, 12);
  }
}

function generate() {
  const gitHash = resolveGitShortHash();
  const buildId = `${gitHash}-${Date.now().toString(36)}`;

  writeFileSync(
    outputPath,
    `// Auto-generated by scripts/generate-app-build-id.mjs — do not edit.\nexport const APP_BUILD_ID = ${JSON.stringify(buildId)};\n`,
    "utf8"
  );
  console.log(`app-build-id: wrote ${buildId}.`);
}

generate();
